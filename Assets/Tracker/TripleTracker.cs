using System;
using System.Collections;
using System.Text;
using TMPro;
using UnityEngine;
using UnityEngine.XR.MagicLeap;
using UnityEngine.InputSystem;
using PeterO.Cbor;
using System.Collections.Generic; // Required for Queue

public class TripleTracker : MonoBehaviour
{
    [SerializeField] private int windowSize = 5; 
    private Queue<Vector3> positionBuffer = new Queue<Vector3>();

    public GameObject trackedObject;

    // marker settings
    public string vrpn_id = "origin";

    [System.Serializable]
    public struct MarkerConfig
    {
        public string id;
        public Vector3 positionOffset;  // physical offset relative to your absolute origin
        public Vector3 rotationOffset;  // rotation offset if the marker faces a different direction
    }

    [Header("Multi-Marker Database")]
    public MarkerConfig[] markerDatabase = new MarkerConfig[3];

    [Header("Automated Scanning")]
    [SerializeField] private float scanInterval = 0.2f; 
    [SerializeField] private float holdToStopDuration = 1.5f;
    private Coroutine _autoScanCoroutine;
    private bool _isScanningAutomated = false;
    private float _triggerPressedTime = 0f;

    // Cache the most recent raw data from Magic Leap's event loop
    private MLMarkerTracker.MarkerData _latestMarkerData;
    private MarkerConfig _activeMarkerConfig;
    private bool _hasFreshData = false;
    private GameObject _headsetVisualMarker;

    // Tracking history to validate dual-marker visibility frames
    private Dictionary<string, float> _markerLastSeenTimestamps = new Dictionary<string, float>();
    private const float FRAME_COINCIDENCE_THRESHOLD = 0.05f; 

    // Calibration threshold counters to prevent extreme spatial jumping artifacts
    private int _processedScanCount = 0;
    private const int INITIAL_WARMUP_FRAMES = 30;
    private const float MAXIMUM_ALLOWED_SHIFT_METERS = 1.5f;
        
    // This was autogenerated and allows developers to create a dynamic
    // instance of an InputActionAsset which includes predefined action maps
    // that correspond to all of the Magic Leap 2's input.
    private MagicLeapInputs _magicLeapInputs;
    
    // This class is an Action Map and was autogenerated by the Unity Input
    // System and includes predefined bindings for the Magic Leap 2 Controller
    // Input Events.
    private MagicLeapInputs.ControllerActions _controllerActions;

    private void Start()
    {
        MLMarkerTracker.ArucoDictionaryName d = MLMarkerTracker.ArucoDictionaryName.DICT_5X5_100;
        MLMarkerTracker.TrackerSettings.CustomProfile customProfile = 
            MLMarkerTracker.TrackerSettings.CustomProfile.Create(
                MLMarkerTracker.FPSHint.Max,                       // high FPS processing
                MLMarkerTracker.ResolutionHint.High,               // high resolution feed
                MLMarkerTracker.CameraHint.World,                  // world tracking cameras
                MLMarkerTracker.FullAnalysisIntervalHint.Max,      // process every frame fully
                MLMarkerTracker.CornerRefineMethod.AprilTag,       // sub-pixel corner solver
                true                                               // edge refinement pass enabled
            );

        MLMarkerTracker.TrackerSettings trackerSettings = MLMarkerTracker.TrackerSettings.Create(
            true, 
            MLMarkerTracker.MarkerType.Aruco_April, 
            0.0f,                   // QR size set to 0 (Unused)
            d, 
            0.082f,                 // ArUco Size (8.2 cm)
            MLMarkerTracker.Profile.Custom, 
            customProfile
        );
    
        // Initialize the MagicLeapInputs like you would Unity's default action map.
        _magicLeapInputs = new MagicLeapInputs();
        _magicLeapInputs.Enable();

        // Initialize the ControllerActions based off the Magic Leap Input
        _controllerActions = new MagicLeapInputs.ControllerActions(_magicLeapInputs);
       
        // track both the press down and the release lift events of the trigger
        _controllerActions.Trigger.started += HandleTriggerPressed;
        _controllerActions.Trigger.canceled += HandleTriggerReleased;
        _controllerActions.Bumper.canceled += HandleOnBumperRelease;

        trackedObject.SetActive(true);
        trackedObject.transform.GetChild(4).gameObject.GetComponent<TextMeshPro>().text = "Release Trigger when aligned with the FLC ORIGIN";

        // start marker tracking with tracker settings object
        _ = MLMarkerTracker.SetSettingsAsync(trackerSettings);
    }

    // subscribe to the event that detects markers
    private void OnEnable()
    {
        MLMarkerTracker.OnMLMarkerTrackerResultsFound += OnTrackerResultsFound;
    }

    private void OnDisable()
    {
        MLMarkerTracker.OnMLMarkerTrackerResultsFound -= OnTrackerResultsFound;
    }

    // just stores the latest marker data as it streams in
    private void OnTrackerResultsFound(MLMarkerTracker.MarkerData data)
    {
        if (data.Type == MLMarkerTracker.MarkerType.Aruco_April)
        {
            string detectedId = data.ArucoData.Id.ToString();
            float currentTime = Time.time;

            // log the current timestamp for this specific marker
            _markerLastSeenTimestamps[detectedId] = currentTime;

            // loop through the database to check if the detected code is one of your active targets
            for (int i = 0; i < markerDatabase.Length; i++)
            {
                if (markerDatabase[i].id == detectedId)
                {
                    // validation rule check: passes instantly if it is the master origin (index 0)
                    if (i == 0)
                    {
                        _latestMarkerData = data;
                        _activeMarkerConfig = markerDatabase[i];
                        _hasFreshData = true;
                        break;
                    }
                    
                    // validation rule check: checking if any other marker co-exists in this exact frame
                    bool seesAnotherMarkerSimultaneously = false;
                    foreach (var pair in _markerLastSeenTimestamps)
                    {
                        if (pair.Key != detectedId && (currentTime - pair.Value) <= FRAME_COINCIDENCE_THRESHOLD)
                        {
                            seesAnotherMarkerSimultaneously = true;
                            break;
                        }
                    }

                    if (seesAnotherMarkerSimultaneously)
                    {
                        _latestMarkerData = data;
                        _activeMarkerConfig = markerDatabase[i];
                        _hasFreshData = true;
                    }
                    break;
                }
            }
        }
    }

    private IEnumerator AutomatedScanRoutine()
    {
        while (_isScanningAutomated)
        {
            // only process if headset has actually captured a frame since our last wait check
            if (_hasFreshData)
            {
                Debug.Log($"[Auto-Scan] Processing frame for marker {_activeMarkerConfig.id} at set rate interval.");

                // updates the 3d headset indicator position directly over the raw tracked code center
                if (_headsetVisualMarker != null)
                {
                    _headsetVisualMarker.transform.position = _latestMarkerData.Pose.position;
                }

                // calculate where the true origin point is based on this marker's offset rule
                Vector3 correctedOriginPosition = _latestMarkerData.Pose.position - _activeMarkerConfig.positionOffset;

                // check if the computed position shift exceeds limits after initial stabilization run completes
                bool allowShift = true;
                if (_processedScanCount >= INITIAL_WARMUP_FRAMES)
                {
                    float deltaDistance = Vector3.Distance(this.transform.position, correctedOriginPosition);
                    if (deltaDistance > MAXIMUM_ALLOWED_SHIFT_METERS)
                    {
                        Debug.LogWarning($"[Auto-Scan] Rejected large spatial jump frame: {deltaDistance}m delta from current state baseline.");
                        allowShift = false;
                    }
                }

                if (allowShift)
                {
                    _processedScanCount++;

                    // queue management for moving window
                    positionBuffer.Enqueue(correctedOriginPosition);
                    if (positionBuffer.Count > windowSize)
                    {
                        positionBuffer.Dequeue();
                    }

                    // mathematical rolling average calculation
                    Vector3 sum = Vector3.zero;
                    foreach (Vector3 pos in positionBuffer)
                    {
                        sum += pos;
                    }
                    this.transform.position = sum / positionBuffer.Count;

                    // smooth rotation filtering taking individual marker alignments into account
                    Quaternion markerRotationOffset = Quaternion.Euler(-90, 0, 180) * Quaternion.Inverse(Quaternion.Euler(_activeMarkerConfig.rotationOffset));
                    Quaternion targetRotation = _latestMarkerData.Pose.rotation * markerRotationOffset;
                    this.transform.rotation = Quaternion.Slerp(this.transform.rotation, targetRotation, 0.2f);

                    // transform sync updates
                    trackedObject.transform.position = this.transform.position;
                    trackedObject.transform.rotation = this.transform.rotation;
                }

                // clear the flag until magic leap updates the data pool again
                _hasFreshData = false;
            }

            // yield control and wait for time delay interval
            yield return new WaitForSeconds(scanInterval);
        }
    }

    // fires instantly when the trigger is pressed down
    private void HandleTriggerPressed(InputAction.CallbackContext obj)
    {
        if (!_isScanningAutomated)
        {
            // turn ON scanning immediately on a single tap
            _isScanningAutomated = true;
            _triggerPressedTime = Time.time;
            _processedScanCount = 0; // reset state tracking checks for initialization execution pathing
            trackedObject.transform.GetChild(4).gameObject.SetActive(true);
            trackedObject.transform.GetChild(4).gameObject.GetComponent<TextMeshPro>().text = "Auto-Scanning Active...";
            
            // builds a small visible green runtime primitive sphere marker
            _headsetVisualMarker = GameObject.CreatePrimitive(PrimitiveType.Sphere);
            _headsetVisualMarker.transform.localScale = Vector3.one * 0.04f;
            _headsetVisualMarker.GetComponent<Renderer>().material.color = Color.green;
            Destroy(_headsetVisualMarker.GetComponent<SphereCollider>());

            _autoScanCoroutine = StartCoroutine(AutomatedScanRoutine());
        }
        else
        {
            // if already scanning, start timing how long the user is holding it down
            _triggerPressedTime = Time.time;
        }
    }

    // fires instantly when the trigger button is released
    private void HandleTriggerReleased(InputAction.CallbackContext obj)
    {
        if (_isScanningAutomated)
        {
            // calculate total held duration
            float holdDuration = Time.time - _triggerPressedTime;

            if (holdDuration >= holdToStopDuration)
            {
                // turned off only if held down longer than threshold
                _isScanningAutomated = false;
                
                if (_autoScanCoroutine != null)
                {
                    StopCoroutine(_autoScanCoroutine);
                }
                
                // cleans up the 3d headset indicator target from memory
                if (_headsetVisualMarker != null)
                {
                    Destroy(_headsetVisualMarker);
                }

                trackedObject.transform.GetChild(4).gameObject.SetActive(false);
                ExecuteOriginSubmit(); 
            }
        }
    }

    // extracted your original trigger-release logic so it fires neatly when scanning turns off
    private void ExecuteOriginSubmit()
    {
        try 
        {
            var n_root = GameObject.FindWithTag("NoodlesRootItem");
            if (n_root) 
            {
                var args = new List<CBORObject> { CBORObject.FromObject(vrpn_id) };
                var comp = n_root.GetComponent<NOODLESRoot>();
                if (comp != null)
                {
                    comp.invoke_method_by_name("get_transform", args, OnRequestReply);
                }                        
            }
        }
        catch (Exception e) 
        {
            Debug.LogException(e);
        }
    }

    private void Update()
    {
        if (_controllerActions.Bumper.IsPressed())
        {
            var controllerPosition = _controllerActions.Position.ReadValue<Vector3>();
            var controllerRotation = _controllerActions.Rotation.ReadValue<Quaternion>();

            try
            {
                var n_root = GameObject.FindWithTag("NoodlesRootItem");
                if (n_root)
                {
                    var rootTransform = n_root.transform;
                    var inverseRootRotation = Quaternion.Inverse(rootTransform.rotation);

                    var relativePos = inverseRootRotation * (controllerPosition - rootTransform.position);
                    var relativeRot = inverseRootRotation * controllerRotation;

                    var args = new List<CBORObject>();
                    args.Add(CBORObject.FromObject(relativePos));

                    // send the components of the RELATIVE rotation, not the absolute one.
                    args.Add(CBORObject.FromObject(relativeRot.x));
                    args.Add(CBORObject.FromObject(relativeRot.y));
                    args.Add(CBORObject.FromObject(relativeRot.z));
                    args.Add(CBORObject.FromObject(relativeRot.w));

                    var comp = n_root.GetComponent<NOODLESRoot>();
                    if (comp != null)
                    {
                        comp.invoke_method_by_name("position_updated", args, NoReply);
                    }
                }
            }
            catch (Exception e)
            {
                Debug.LogException(e);
            }
        }
    }

    private void HandleOnBumperRelease(InputAction.CallbackContext obj)
    {
        bool bumperDown = obj.ReadValueAsButton();

        try 
        {
            var n_root = GameObject.FindWithTag("NoodlesRootItem");

            if (n_root) {
                var args = new List<CBORObject>();
                var comp = n_root.GetComponent<NOODLESRoot>();

                if (comp != null)
                {
                    comp.invoke_method_by_name("position_set", args, NoReply);
                }                        
            }
        }
        catch (Exception e) 
        {
            Debug.LogException(e);
        }
    }

    private void OnRequestReply(CBORObject reply) {
        var transform_array = reply["result"];

        var offset = new Vector3(
            transform_array[0].ToObject<float>(),
            transform_array[1].ToObject<float>(), 
            -transform_array[2].ToObject<float>()
        );

        var rotation = new Quaternion(
            transform_array[3].ToObject<float>(),
            transform_array[4].ToObject<float>(), 
            -transform_array[5].ToObject<float>(),
            -transform_array[6].ToObject<float>()
        );

        var n_root = GameObject.FindWithTag("NoodlesRootItem");
        var n_room_offset = GameObject.FindWithTag("OriginOffsetItem");
        var indicator = GameObject.FindWithTag("CoordinateIndicator");

        if (n_root == null || n_room_offset == null || indicator == null)
        {
            Debug.LogWarning("Unable to find root or root offset nodes, we cannot properly set the origin for this client!");
            return;
        }

        n_root.transform.localPosition = offset;
        n_room_offset.transform.localRotation = rotation;

        var tf_a = n_root.transform;
        var tf_b = transform;

        var indicator_pos = tf_a.InverseTransformPoint(tf_b.position);
        var indicator_rot = Quaternion.Inverse(tf_a.rotation) * tf_b.rotation;

        indicator.transform.SetLocalPositionAndRotation(indicator_pos, indicator_rot);
    }

    private void NoReply(CBORObject reply) {
    }
}